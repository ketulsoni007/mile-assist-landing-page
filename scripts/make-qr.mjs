// Builds crisp QR codes for the two store links as SVG path data (components/svg/qr-data.ts).
// usage: node scripts/make-qr.mjs   (re-run if the store URLs in lib/seo.ts change)
import fs from "fs";
import QRCode from "qrcode";

const links = {
  play: "https://play.google.com/store/apps/details?id=com.milesassist.driver",
  apple: "https://apps.apple.com/in/app/miles-assist-driver/id6758386740",
};
const out = {};
for (const [k, url] of Object.entries(links)) {
  const qr = QRCode.create(url, { errorCorrectionLevel: "M" });
  const n = qr.modules.size;
  let d = "";
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) if (qr.modules.get(y, x)) d += `M${x} ${y}h1v1h-1z`;
  out[k] = { size: n, path: d };
  console.log(k, n);
}
fs.writeFileSync("components/svg/qr-data.ts", `// GENERATED by scripts/make-qr.mjs. Do not edit by hand.\nexport const QR = ${JSON.stringify(out)} as const;\n`);
