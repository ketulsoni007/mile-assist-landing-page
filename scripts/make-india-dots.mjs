// Dotted map of India (Natural Earth 50m country shape via world-atlas, dev-only) + city pins.
// Output: components/svg/india-data.ts (one compact path). usage: node scripts/make-india-dots.mjs
import fs from "fs";
import { createRequire } from "module";
import { feature } from "topojson-client";
import { geoContains, geoMercator } from "d3-geo";
const require = createRequire(import.meta.url);
const topo = require("world-atlas/countries-50m.json");
const india = feature(topo, topo.objects.countries).features.find((f) => f.id === "356");
const W = 600, H = 660;
const proj = geoMercator().fitExtent([[10, 10], [W - 10, H - 10]], india);
const STEP = 9;
let d = "", n = 0;
for (let y = STEP / 2; y < H; y += STEP)
  for (let x = STEP / 2 + ((Math.round(y / STEP) % 2) * STEP) / 2; x < W; x += STEP) {
    const ll = proj.invert([x, y]);
    if (ll && geoContains(india, ll)) { d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`; n++; }
  }
const cities = { Delhi: [77.21, 28.61], Jaipur: [75.79, 26.91], Ahmedabad: [72.57, 23.02], Mumbai: [72.88, 19.08], Pune: [73.86, 18.52], Bengaluru: [77.59, 12.97], Chennai: [80.27, 13.08], Hyderabad: [78.49, 17.39], Kolkata: [88.36, 22.57], Lucknow: [80.95, 26.85], Indore: [75.86, 22.72], Surat: [72.83, 21.17] };
const pins = Object.entries(cities).map(([name, ll]) => { const [x, y] = proj(ll); return { name, x: +x.toFixed(1), y: +y.toFixed(1) }; });
fs.writeFileSync("components/svg/india-data.ts", `// GENERATED by scripts/make-india-dots.mjs. Do not edit by hand.\nexport const INDIA = { w: ${W}, h: ${H}, dots: ${n}, path: ${JSON.stringify(d)}, pins: ${JSON.stringify(pins)} } as const;\n`);
console.log("dots", n, "KB", (d.length / 1024).toFixed(1), pins.map((p) => p.name + ":" + p.x + "," + p.y).join(" "));
