// Builds a dotted world map: lays a grid over the world and keeps the dots that fall on land
// (Natural Earth land shapes via the world-atlas package, dev-only). Output is one compact SVG path
// (each dot is a zero-length round-capped segment), so the browser gets ~10 KB and no map library.
// usage: node scripts/make-world-dots.mjs
import fs from "fs";
import { createRequire } from "module";
import { feature } from "topojson-client";
import { geoContains, geoEquirectangular } from "d3-geo";
const require = createRequire(import.meta.url);

const land = feature(require("world-atlas/land-110m.json"), require("world-atlas/land-110m.json").objects.land);
const W = 1000, H = 500;
const proj = geoEquirectangular().fitExtent([[0, 0], [W, H]], { type: "Sphere" });
const STEP = 9; // dot spacing in map units

let d = "";
let n = 0;
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2 + ((Math.round(y / STEP) % 2) * STEP) / 2; x < W; x += STEP) {
    const ll = proj.invert([x, y]);
    if (!ll || ll[1] < -58 || ll[1] > 78) continue; // drop Antarctica and the far Arctic
    if (geoContains(land, ll)) { d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`; n++; }
  }
}
const cities = { Delhi: [77.2, 28.6], Mumbai: [72.9, 19.1], Bengaluru: [77.6, 12.97], Kolkata: [88.4, 22.6], Chennai: [80.3, 13.1], Ahmedabad: [72.6, 23.0] };
const pins = Object.entries(cities).map(([name, ll]) => ({ name, x: +proj(ll)[0].toFixed(1), y: +proj(ll)[1].toFixed(1) }));
fs.writeFileSync("components/svg/world-data.ts", `// GENERATED by scripts/make-world-dots.mjs. Do not edit by hand.\nexport const WORLD = { w: ${W}, h: ${H}, dots: ${n}, path: ${JSON.stringify(d)}, pins: ${JSON.stringify(pins)} } as const;\n`);
console.log("dots", n, "KB", (d.length / 1024).toFixed(1), pins);
