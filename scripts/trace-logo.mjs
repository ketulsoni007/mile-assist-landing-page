// Converts the registered logo (flat colours, transparent PNG) into an inline SVG React component
// whose navy parts are driven by CSS variables, so the logo can adapt to dark mode.
// Shapes and light-theme colours are the logo's own; only dark-mode tones are added.
// usage: node scripts/trace-logo.mjs
import sharp from "sharp";
import fs from "fs";
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const IT = require("imagetracerjs");

const SRC = "public/brand/logo-horizontal.png";
const SCALE = 0.5; // trace at half resolution (2841 x 569): plenty for a header logo, half the path data
const { data: full, info: fi } = await sharp(SRC).raw().toBuffer({ resolveWithObject: true });
const W = Math.round(fi.width * SCALE), H = Math.round(fi.height * SCALE);
const { data, info } = await sharp(SRC).resize(W, H, { kernel: "lanczos3" }).raw().toBuffer({ resolveWithObject: true });
const C = info.channels;

// where each navy part lives (in traced coordinates)
const WHEEL = { x0: 90, y0: 0, x1: 420, y1: 340 };
const inBox = (b, x, y) => x >= b.x0 && x <= b.x1 && y >= b.y0 && y <= b.y1;
const part = (x, y) => (x > 1000 ? "word" : inBox(WHEEL, x, y) ? "wheel" : "road");

// sample the true navy of each part for the light theme
const sums = { word: [0, 0, 0, 0], wheel: [0, 0, 0, 0], road: [0, 0, 0, 0] };
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  const i = (y * W + x) * C;
  if (data[i + 3] < 250) continue;
  const r = data[i], g = data[i + 1], b = data[i + 2];
  if (!(b > r + 40 && r < 40 && g < 70 && b < 130)) continue; // navy only
  const s = sums[part(x, y)]; s[0] += r; s[1] += g; s[2] += b; s[3]++;
}
const hex = (s) => "#" + [0, 1, 2].map((k) => Math.round(s[k] / s[3]).toString(16).padStart(2, "0")).join("");
const light = { word: hex(sums.word), wheel: hex(sums.wheel), road: hex(sums.road) };
console.log("light navy tones", light);

// build the image on a magenta key colour and snap every pixel to the logo's flat palette
const NAVY = [5, 33, 86], SLATE = [118, 136, 155], ORANGE = [255, 90, 0], WHITE = [255, 255, 255], KEY = [255, 0, 255];
const pal = [KEY, NAVY, SLATE, ORANGE, WHITE];
const rgba = new Uint8ClampedArray(W * H * 4);
for (let i = 0; i < W * H; i++) {
  const a = data[i * C + 3];
  const c = a < 128 ? KEY : [data[i * C], data[i * C + 1], data[i * C + 2]];
  rgba[i * 4] = c[0]; rgba[i * 4 + 1] = c[1]; rgba[i * 4 + 2] = c[2]; rgba[i * 4 + 3] = 255;
}
let svg = IT.imagedataToSVG({ width: W, height: H, data: rgba }, {
  pal: pal.map(([r, g, b]) => ({ r, g, b, a: 255 })), colorsampling: 0, numberofcolors: pal.length,
  ltres: 0.8, qtres: 0.8, pathomit: 6, rightangleenhance: false, blurradius: 0, strokewidth: 1, roundcoords: 1, viewbox: true, desc: false, layering: 0,
});

// turn the traced paths into JSX, tagging the navy parts with theme variables
const paths = [];
const re = /<path[^>]*?fill="rgb\((\d+),(\d+),(\d+)\)"[^>]*?d="([^"]+)"[^>]*\/>/g;
let m;
while ((m = re.exec(svg))) {
  const [r, g, b] = [+m[1], +m[2], +m[3]], d = m[4];
  // the tracer averages its palette, so snap each path to the nearest flat logo colour
  const dist = (c) => (c[0] - r) ** 2 + (c[1] - g) ** 2 + (c[2] - b) ** 2;
  const nearest = pal.reduce((best, c) => (dist(c) < dist(best) ? c : best));
  if (nearest === KEY) continue;
  let fill;
  if (nearest === ORANGE) fill = "#ff5a00";
  else if (nearest === SLATE) fill = "#76889b";
  else if (nearest === WHITE) fill = "#ffffff";
  else {
    // navy: classify by where the path sits
    const nums = d.match(/-?\d+(\.\d+)?/g).map(Number);
    let sx = 0, sy = 0, n = 0;
    for (let k = 0; k + 1 < nums.length; k += 2) { sx += nums[k]; sy += nums[k + 1]; n++; }
    fill = `var(--lg-${part(sx / n, sy / n)})`;
  }
  paths.push({ fill, d });
}
console.log("paths", paths.length);

const body = paths.map((p) => `<path fill="${p.fill}" stroke="${p.fill}" strokeWidth="1" d="${p.d}" />`).join("\n      ");
const tsx = `// GENERATED by scripts/trace-logo.mjs from public/brand/logo-horizontal.png. Do not edit by hand.
// Same shapes and colours as the registered logo; the navy parts read CSS variables so they can adapt to dark mode.

export function LogoHorizontal({ className, title = "Miles Assist - From Route to Relief" }: { className?: string; title?: string }) {
  return (
    <svg viewBox="0 0 ${W} ${H}" className={className} role="img" aria-label={title} xmlns="http://www.w3.org/2000/svg">
      ${body}
    </svg>
  );
}
`;
fs.mkdirSync("components/brand", { recursive: true });
fs.writeFileSync("components/brand/LogoHorizontal.tsx", tsx);
fs.writeFileSync("components/brand/logo-light-tones.json", JSON.stringify(light));
console.log("component KB", (tsx.length / 1024).toFixed(0));
